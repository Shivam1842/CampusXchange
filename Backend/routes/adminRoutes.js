import express from "express";
import { protect } from "../middleware/authMiddleware.js";
import { authorize } from "../middleware/roleMiddleware.js";
import { getMetrics, getRegistrations, getActivity, getPopularSkills, getUsers, getProjects, getReports, getAuditLogs, verifyUser, suspendUser, deleteUser, moderateProject, updateReport, getVerificationDocuments, reviewVerificationDocument } from "../controllers/adminController.js";
import { createVerificationDownload } from "../controllers/verificationController.js";
const router = express.Router();
router.use(protect, authorize("admin"));
router.get("/metrics", getMetrics);
router.get("/registrations", getRegistrations);
router.get("/activity", getActivity);
router.get("/popular-skills", getPopularSkills);
router.get("/users", getUsers);
router.get("/projects", getProjects);
router.get("/reports", getReports);
router.get("/audit-logs", getAuditLogs);
router.get("/verification-documents", getVerificationDocuments);
router.patch("/verification-documents/:id", reviewVerificationDocument);
router.get("/verification-documents/:id/download", createVerificationDownload);
router.patch("/users/:id/verify", verifyUser);
router.patch("/users/:id/suspend", suspendUser);
router.delete("/users/:id", deleteUser);
router.patch("/projects/:id/moderate", moderateProject);
router.patch("/reports/:id", updateReport);
export default router;
